def V(n, d, c=None, s=None, a=None, ps=None, st=None, rg=None, set=None, debt=None, tag=None):
    v = {"n": n, "d": d}
    if c is not None: v["c"] = float(c)
    if s: v["s"] = s
    if a: v["a"] = a
    if st: v["st"] = st
    if rg: v["rg"] = rg
    if set: v["set"] = set
    if debt is not None: v["debt"] = float(debt)
    if ps: v["psa"] = ps          # реакции партий по архетипам; будут преобразованы в слоты
    if tag: v["tag"] = tag        # (измерение, знак) для влияния на отношения соседей
    return v
def T(id, cat, name, desc, variants, fund=False):
    return {"id": id, "cat": cat, "name": name, "desc": desc, "v": variants, "fund": fund}

