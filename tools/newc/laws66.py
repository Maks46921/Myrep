def num(x):
    return ("%.2f" % x).rstrip("0").rstrip(".") if x != int(x) else "%.1f" % x


def d(m):
    return "{" + ", ".join('"%s": %s' % (k, num(v)) for k, v in m.items()) + "}"


def q(s):
    assert '"' not in s and "\\" not in s, s
    return '"' + s + '"'


def emit():
    out = []
    for cc in CC:
        out.append('\t"%s": [' % cc)
        tps = DATA[cc]
        for ti, t in enumerate(tps):
            out.append('\t{"id": %s, "cat": %d, "name": %s, "desc": %s, "v": [' % (q(t["id"]), t["cat"], q(t["name"]), q(t["desc"])))
            for vi, v in enumerate(t["v"]):
                end = "}"
                if vi == len(t["v"]) - 1:
                    end = "}]}" + ("]," if ti == len(tps) - 1 else ",")
                else:
                    end = "},"
                if v["c"] is None:
                    out.append('\t\t{"n": %s, "d": %s%s' % (q(v["n"]), q(v["d"]), end if vi < len(t["v"]) - 1 else "}]}" + ("]," if ti == len(tps) - 1 else ",")))
                else:
                    extra = ""
                    if v["st"]:
                        extra = ', "st": %s' % d(v["st"])
                    last = vi == len(t["v"]) - 1
                    out.append('\t\t{"n": %s, "d": %s, "c": %.1f, "s": %s, "a": %s%s%s' % (
                        q(v["n"]), q(v["d"]), v["c"], d(v["s"]), d(v["a"]), extra,
                        ("}]}" + ("]," if ti == len(tps) - 1 else ",")) if last else "},"))
    return "\n".join(out)


