def calibrate():
    """Смещения REG_BIAS и лояльность регионов так, чтобы старт воспроизводил региональные итоги 2024, подогнанные под опрос POLL."""
    n = len(REG_RAW)
    Es = [norm([max(x, 0.05) for x in r[-1]]) for r in REG_RAW]
    pw = [r[3] for r in REG_RAW]; s = sum(pw); pw = [x / s for x in pw]
    fct = [1.0] * 10
    for _ in range(400):
        nat = [0.0] * 10
        for i in range(n):
            v = norm([Es[i][p] * fct[p] for p in range(10)])
            for p in range(10): nat[p] += pw[i] * v[p]
        for p in range(10): fct[p] *= (POLL[p] / 100.0) / max(nat[p], 1e-9)
    T = [norm([Es[i][p] * fct[p] for p in range(10)]) for i in range(n)]
    gw = GROUP_WEIGHT
    loy = [max(15.0, min(85.0, LOY_MEAN + (T[i][0] * 100.0 - POLL[0]) * 1.2)) for i in range(n)]
    mixes = []
    for r in REG_RAW:
        m = {g: gw[g] * r[15].get(g, 1.0) for g in GROUPS}
        t = sum(m.values()); mixes.append({g: m[g] / t for g in GROUPS})
    RP = REGIONAL_P
    def shares(i, bias):
        r = REG_RAW[i]; sh = [0.0] * 10
        for g in GROUPS:
            eff = min(100.0, max(5.0, GROUP_BASE[g] + (loy[i] - 50.0) * 0.5))
            w = []
            for p in range(10):
                v = LEAN[g][p]
                if p == 0: v *= (eff / 50.0) ** 3
                elif p == 9: v *= max(0.2, min(2.0, (100.0 - eff) / 50.0)) ** 2
                elif p == RP: v *= (1.0 + r[6] / 40.0) * (0.6 + 0.9 * r[8])
                v *= bias[i][p]; w.append(v)
            t = sum(w)
            for p in range(10): sh[p] += mixes[i][g] * w[p] / t
        return sh
    bias = [[1.0] * 10 for _ in range(n)]
    for _ in range(600):
        err = 0
        for i in range(n):
            sh = shares(i, bias)
            for p in range(10):
                ratio = T[i][p] / max(sh[p], 1e-9)
                err = max(err, abs(ratio - 1)); bias[i][p] *= ratio ** 0.7
            m = bias[i][0]; bias[i] = [b / m for b in bias[i]]
        if err < 1e-6: break
    return bias, T, loy

